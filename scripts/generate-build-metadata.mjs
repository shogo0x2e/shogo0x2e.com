import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "src/generated/buildMetadata.ts");
const cloudflareCommit = process.env.CF_PAGES_COMMIT_SHA?.trim();
const validCommit = /^[0-9a-f]{7,40}$/i.test(cloudflareCommit ?? "")
  ? cloudflareCommit
  : undefined;

function git(...args) {
  return execFileSync("git", args, {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();
}

let commitSha = validCommit;
let lastUpdated;
let source = "build-time";

try {
  commitSha ??= git("rev-parse", "HEAD");
  lastUpdated = git("show", "-s", "--format=%cI", commitSha);
  source = validCommit ? "cloudflare-pages-commit" : "git-head";
} catch {
  lastUpdated = new Date().toISOString();
}

const normalizedLastUpdated = new Date(lastUpdated).toISOString();
const contents = `// Generated by scripts/generate-build-metadata.mjs. Do not edit.\nexport const buildMetadata = ${JSON.stringify(
  {
    lastUpdated: normalizedLastUpdated,
    commitSha: commitSha ?? null,
    source,
  },
  null,
  2,
)} as const;\n`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, contents, "utf8");

console.log(`Generated build metadata from ${source}: ${normalizedLastUpdated}`);
